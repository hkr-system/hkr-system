-- /apply landing (Oct 27 2026): tracking of the shared link, public reference code,
-- "how did you hear about us → other" text, and the public WhatsApp number shown on the thank-you page.

alter table public.lead_form_submissions
  add column if not exists src          text,          -- channel in the shared link (wa, email, linkedin, expo…)
  add column if not exists ref          text,          -- owner / campaign in the shared link
  add column if not exists utm          jsonb not null default '{}',
  add column if not exists heard_other  text,
  add column if not exists ref_no       bigint generated by default as identity;  -- public reference HKR-YY-NNNN

create index if not exists lead_form_submissions_ref_no_idx on public.lead_form_submissions (ref_no);

insert into public.settings (key, category, label, value, confidential, sort_order, description) values
  ('apply_whatsapp_public', 'landing', 'Public WhatsApp number', '""', false, 500,
   'Shown on the thank-you page of /apply when the lead''s market has no WhatsApp number assigned (wa_number_by_market). International format with +. Empty = the WhatsApp button is hidden.')
on conflict (key) do nothing;
